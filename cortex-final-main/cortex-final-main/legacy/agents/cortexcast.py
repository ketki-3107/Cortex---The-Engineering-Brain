"""
CORTEXCAST agent: triggered on demand via POST /cortexcast. Reads all CORTEX memories,
analyses staleness and health, and creates a formatted health report as a new
GitLab issue.
"""

import json
import logging
from datetime import datetime, timezone

from legacy.core.gitlab_client import GitLabClient
from legacy.core.claude_client import ClaudeClient
from legacy.core.memory import MemoryStore

logger = logging.getLogger("cortex.cortexcast")


_REPLAY_KEYWORDS = ("replay", "history of", "evolution of")


def _wants_replay(user_goal: str) -> bool:
    lowered = user_goal.lower()
    return any(kw in lowered for kw in _REPLAY_KEYWORDS)


def _render_expertise_section(expertise_map: list[dict]) -> list[str]:
    """Render the Expertise Discovery section from expertise_map."""
    parts = [
        "## 👤 Expertise Map",
        "",
        "Decision owners derived from `decided_by` fields across all memories:",
        "",
        "| Person | Memories | Primary Area | Top Files |",
        "|--------|----------|--------------|-----------|",
    ]
    for entry in expertise_map:
        person = entry.get("person", "")
        memory_ids = entry.get("memory_ids") or []
        top_files = entry.get("top_files") or []
        primary_category = entry.get("primary_category", "—")
        ids_str = ", ".join(f"#{mid}" for mid in memory_ids)
        files_str = ", ".join(f"`{f}`" for f in top_files[:3])
        parts.append(f"| {person} | {ids_str} | {primary_category} | {files_str} |")
    parts.append("")
    return parts


def _render_replay_section(chains: list[dict]) -> list[str]:
    """Render the Decision Replay section from supersedes chains."""
    parts = [
        "## 🔁 Decision Replay",
        "",
        "Evolution chains reconstructed from `Supersedes` links — oldest to newest:",
        "",
    ]
    for i, chain_obj in enumerate(chains, 1):
        chain = chain_obj.get("chain") or []
        summary = chain_obj.get("summary", "")
        chain_str = " → ".join(f"Memory #{mid}" for mid in chain)
        parts.append(f"**Chain {i}:** {chain_str}")
        if summary:
            parts.append(f"> {summary}")
        parts.append("")
    return parts


async def run_cortexcast(user_goal: str = "") -> None:
    """
    Run cortexCAST: fetch all memories, call Claude for health analysis, and
    create a GitLab issue with the formatted health report.

    user_goal: optional triggering text (e.g. from a note) used to decide
               whether to include the Decision Replay section.
    """
    try:
        # — Step 1: Initialise clients —
        gitlab = GitLabClient()
        claude = ClaudeClient()
        memory_store = MemoryStore(gitlab)

        # — Step 2: Fetch all memories —
        all_memories = memory_store.get_all_memories()

        today_date = datetime.now(timezone.utc).strftime("%Y-%m-%d")

        if not all_memories:
            gitlab.create_issue(
                title=f"🧠 CORTEX Health Report — {today_date}",
                description=(
                    f"# 🧠 CORTEX Health Report — {today_date}\n\n"
                    "## No Memories Stored Yet\n\n"
                    "CORTEX is active and listening but no architectural decisions have been "
                    "captured yet.\n\n"
                    "**How to start building institutional memory:**\n"
                    "- CORTEX automatically captures decisions when MRs are merged\n"
                    "- Make sure the webhook is configured and active\n"
                    "- Decisions are extracted from MR discussion threads\n\n"
                    "*Generated by CORTEX CORTEXCAST*"
                ),
                labels=["cortex-health"],
            )
            return

        # — Step 3: Fetch recent MR titles —
        try:
            recent_mrs = gitlab.get_recent_mrs(count=20)
            recent_mr_titles = [m.get("title", "") for m in recent_mrs if m.get("title")]
        except Exception as e:
            logger.warning("CORTEXCAST: Could not fetch recent MRs: %s", e)
            recent_mr_titles = []

        # — Step 4: Build the user message for Claude —
        memory_blocks = []
        for m in all_memories:
            governs = ", ".join(m.get("governs_files") or [])
            decided_by = ", ".join(m.get("decided_by") or [])
            memory_blocks.append(
                f"---\n"
                f"Memory #{m.get('id', '')}\n"
                f"Date captured: {m.get('date', '')}\n"
                f"Decision: {m.get('decision', '')}\n"
                f"Rejected: {m.get('rejected', '')}\n"
                f"Reason: {m.get('reason', '')}\n"
                f"Future implication: {m.get('future_implication', '')}\n"
                f"Governs files: {governs}\n"
                f"Decided by: {decided_by}\n"
                f"Confidence: {m.get('confidence', '')}\n"
                f"Status: {m.get('status', '')}\n"
                f"Supersedes: {m.get('supersedes', '')}\n"
                f"---"
            )
        all_memories_block = "\n\n".join(memory_blocks)

        if recent_mr_titles:
            recent_titles_block = "\n".join(f"{i+1}. {t}" for i, t in enumerate(recent_mr_titles))
        else:
            recent_titles_block = "No recent MRs found."

        user_message = (
            f"CURRENT DATE: {today_date}\n\n"
            f"ALL MEMORIES:\n{all_memories_block}\n\n"
            f"RECENT MR TITLES (last 20):\n{recent_titles_block}"
        )

        # — Step 5: Call Claude —
        system_prompt = claude.load_prompt("cortexcast")
        response_str = claude.call(
            system_prompt=system_prompt,
            user_message=user_message,
            max_tokens=3000,
        )

        # — Step 6: Parse Claude response —
        # Claude may wrap JSON in markdown code blocks, so extract it first
        json_str = response_str
        if json_str.strip().startswith("```"):
            # Extract JSON from markdown code block
            lines = json_str.strip().split("\n")
            if lines[0].startswith("```"):
                lines = lines[1:]  # Remove opening ```
            if lines and lines[-1].strip().startswith("```"):
                lines = lines[:-1]  # Remove closing ```
            json_str = "\n".join(lines)
        
        try:
            result = json.loads(json_str)
        except json.JSONDecodeError as e:
            logger.error("CORTEXCAST: Failed to parse Claude response: %s. Raw: %s", e, response_str)
            gitlab.create_issue(
                title=f"🧠 CORTEX Health Report — {today_date} (Parse Error)",
                description=response_str,
                labels=["cortex-health"],
            )
            return

        # — Step 7: Build the formatted issue body —
        total_memories = result.get("total_memories", 0)
        healthy_count = result.get("healthy_count", 0)
        review_count = result.get("review_count", 0)
        stale_count = result.get("stale_count", 0)
        health_summary = result.get("health_summary", "")
        top_recommendation = result.get("top_recommendation", "")
        stale_memories = result.get("stale_memories") or []
        review_memories = result.get("review_memories") or []
        di = result.get("decision_intelligence") or {}
        supersedes_chains = result.get("supersedes_chains") or []
        expertise_map = result.get("expertise_map") or []

        body_parts = [
            f"# 🧠 CORTEX Health Report — {today_date}",
            "",
            "## Summary",
            "",
            "| Metric | Count |",
            "|--------|-------|",
            f"| Total memories | {total_memories} |",
            f"| Healthy | {healthy_count} |",
            f"| Needs review | {review_count} |",
            f"| Potentially stale | {stale_count} |",
            "",
            "## Overall Health",
            health_summary,
            "",
            f"**Top recommendation:** {top_recommendation}",
            "",
        ]

        # — Decision Intelligence section —
        if di:
            conf = di.get("confidence_distribution") or {}
            status_dist = di.get("status_distribution") or {}
            hotspots = di.get("hotspot_files") or []
            broad = di.get("broad_decisions") or []
            coverage_rec = di.get("coverage_recommendation", "")
            governed_file_count = di.get("governed_file_count", 0)

            body_parts += [
                "",
                "## 🔍 Decision Intelligence",
                "",
                "| Metric | Value |",
                "|--------|-------|",
                f"| Files governed by at least one memory | {governed_file_count} |",
                f"| HIGH confidence decisions | {conf.get('HIGH', 0)} |",
                f"| MEDIUM confidence decisions | {conf.get('MEDIUM', 0)} |",
                f"| LOW confidence decisions | {conf.get('LOW', 0)} |",
                f"| Active memories | {status_dist.get('Active', 0)} |",
                f"| Superseded memories | {status_dist.get('Superseded', 0)} |",
                "",
            ]

            if hotspots:
                body_parts += [
                    "### Coverage Hotspots",
                    "",
                    "Files governed by 3 or more memories — potential fragility or high churn:",
                    "",
                ]
                for h in hotspots:
                    ids_str = ", ".join(f"#{mid}" for mid in (h.get("memory_ids") or []))
                    body_parts.append(
                        f"- **{h.get('file', '')}** — {h.get('memory_count', 0)} memories "
                        f"({ids_str}): {h.get('risk_note', '')}"
                    )
                body_parts.append("")

            if broad:
                body_parts += [
                    "### Architecturally Broad Decisions",
                    "",
                    "Memories governing 3 or more files — cross-cutting constraints:",
                    "",
                ]
                for b in broad:
                    files_str = ", ".join(b.get("files") or [])
                    body_parts.append(
                        f"- **Memory #{b.get('memory_id', '')}** ({b.get('file_count', 0)} files — "
                        f"{files_str}): {b.get('decision_summary', '')}"
                    )
                body_parts.append("")

            if coverage_rec:
                body_parts += [
                    "### Coverage Recommendation",
                    "",
                    coverage_rec,
                    "",
                ]

        if supersedes_chains and _wants_replay(user_goal):
            body_parts += _render_replay_section(supersedes_chains)
        elif supersedes_chains:
            body_parts.append(
                f"*{len(supersedes_chains)} decision evolution chain(s) on record — "
                "ask `cortex: replay` to see the full history.*"
            )
            body_parts.append("")

        if expertise_map:
            body_parts += _render_expertise_section(expertise_map)

        body_parts.append("")

        if stale_memories:
            body_parts.append("## ⚠️ Stale Memories — Action Required")
            body_parts.append("")
            for s in stale_memories:
                mem_id = s.get("memory_id", "")
                reason_stale = s.get("reason_stale", "")
                urgency = s.get("urgency", "")
                suggested_action = s.get("suggested_action", "")
                body_parts.append(f"### Memory #{mem_id}")
                body_parts.append(f"**Why potentially stale:** {reason_stale}")
                body_parts.append(f"**Urgency:** {urgency}")
                body_parts.append(f"**Suggested action:** {suggested_action}")
                body_parts.append("")

        if review_memories:
            body_parts.append("## 🔍 Memories Worth Reviewing")
            body_parts.append("")
            for r in review_memories:
                mem_id = r.get("memory_id", "")
                reason_review = r.get("reason_review", "")
                suggested_action = r.get("suggested_action", "")
                body_parts.append(f"### Memory #{mem_id}")
                body_parts.append(f"**Why:** {reason_review}")
                body_parts.append(f"**Suggested action:** {suggested_action}")
                body_parts.append("")

        if not stale_memories and not review_memories:
            body_parts.append("## ✅ All Memories Healthy")
            body_parts.append("")
            body_parts.append(
                "No stale or at-risk memories detected. Your institutional memory is in "
                "good shape."
            )
            body_parts.append("")

        body_parts.append("## Memory Growth")
        body_parts.append(f"Total memories stored: **{total_memories}**")
        body_parts.append(f"Report generated: {today_date}")
        body_parts.append("")
        body_parts.append("---")
        body_parts.append("*Generated by CORTEX CORTEXCAST — your institutional memory health agent*")
        body_parts.append("*To run another health check: POST /cortexcast*")

        formatted_body = "\n".join(body_parts)

        # — Step 8: Create the GitLab issue —
        created = gitlab.create_issue(
            title=f"🧠 CORTEX Health Report — {today_date}",
            description=formatted_body,
            labels=["cortex-health"],
        )
        iid = created.get("iid")
        logger.info("CORTEXCAST complete. Health report created as issue #%s.", iid)

    except Exception as e:
        logger.error("CORTEXCAST failed: %s", e, exc_info=True)
        try:
            gitlab = GitLabClient()
            gitlab.create_issue(
                title="🧠 CORTEX Health Report — ERROR",
                description=f"CORTEXCAST encountered an error: {str(e)}\n\nCheck server logs.",
                labels=["cortex-health"],
            )
        except Exception:
            pass

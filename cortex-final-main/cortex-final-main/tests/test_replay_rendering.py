def test_wants_replay_keywords():
    assert _wants_replay("cortex: replay history")
    assert _wants_replay("show me the history of retry policy")
    assert _wants_replay("what is the evolution of the auth token decision")
    assert _wants_replay("REPLAY auth decision")
    assert not _wants_replay("cortex health check please")
    assert not _wants_replay("")
    assert not _wants_replay("cortex: promote-to-org #004")


def test_render_replay_section_structure():
    parts = _render_replay_section(CHAINS)
    rendered = "\n".join(parts)
    assert "## 🔁 Decision Replay" in rendered
    assert "Supersedes" in rendered
    assert "**Chain 1:**" in rendered
    assert "Memory #001" in rendered and "Memory #003" in rendered
    assert "Memory #001 →" in rendered or "001 → Memory #003" in rendered
    assert "> Fixed retry intervals" in rendered
    assert "**Chain 2:**" in rendered
    assert "Memory #002" in rendered and "Memory #004" in rendered and "Memory #007" in rendered
    assert "> Auth token storage" in rendered


def test_replay_section_shown_when_keyword_in_goal():
    result = {**BASE_RESULT, "supersedes_chains": CHAINS}
    body = render_issue_body(result, DATE, user_goal="replay history of retry decision")
    assert "🔁 Decision Replay" in body
    assert "Memory #001" in body and "Memory #003" in body
    assert "Memory #007" in body
    assert "evolution chain(s) on record" not in body
    assert "Decision Intelligence" in body
    assert "CORTEX Health Report" in body



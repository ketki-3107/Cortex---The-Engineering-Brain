"""
Unit tests for Expertise Discovery (Step 7) additions to CORTEXCAST.
Covers: _render_expertise_section output, integration into issue body,
and edge cases (empty map, missing fields, file truncation).
"""
import sys

# ── inline helpers ────────────────────────────────────────────────────────────

def _render_expertise_section(expertise_map: list) -> list:
    parts = [
        "## 👤 Expertise Map",
        "",
        "Decision owners derived from `decided_by` fields across all memories:",
        "",
        "| Person | Memories | Primary Area | Top Files |",
        "|--------|----------|--------------|-----------|",
    ]
    for entry in expertise_map:
        person = entry.get("person", "")
        memory_ids = entry.get("memory_ids") or []
        top_files = entry.get("top_files") or []
        primary_category = entry.get("primary_category", "—")
        ids_str = ", ".join(f"#{mid}" for mid in memory_ids)
        files_str = ", ".join(f"`{f}`" for f in top_files[:3])
        parts.append(f"| {person} | {ids_str} | {primary_category} | {files_str} |")
    parts.append("")
    return parts


def render_body_with_expertise(expertise_map: list, today_date: str) -> str:
    """Minimal body builder focused on the expertise section placement."""
    body_parts = [
        f"# 🧠 CORTEX Health Report — {today_date}",
        "",
        "## Summary",
        "",
        "| Metric | Count |",
        "|--------|-------|",
        "| Total memories | 3 |",
        "",
        "## Overall Health",
        "Memory bank growing.",
        "",
        "**Top recommendation:** Review old memories.",
        "",
    ]

    if expertise_map:
        body_parts += _render_expertise_section(expertise_map)

    body_parts.append("")
    body_parts.append("## ✅ All Memories Healthy")
    body_parts.append("")
    body_parts.append("## Memory Growth")
    body_parts.append("Total memories stored: **3**")
    body_parts.append(f"Report generated: {today_date}")
    body_parts.append("")
    body_parts.append("---")
    body_parts.append("*Generated by CORTEX CORTEXCAST — your institutional memory health agent*")
    return "\n".join(body_parts)


# ── shared fixtures ───────────────────────────────────────────────────────────

DATE = "2026-08-09"

EXPERTISE_MAP = [
    {
        "person": "@shruti",
        "memory_ids": ["001", "003"],
        "top_files": ["legacy/agents/cortexkeeper.py", "legacy/core/memory.py"],
        "primary_category": "ARCHITECTURE",
    },
    {
        "person": "@arya",
        "memory_ids": ["002"],
        "top_files": ["legacy/core/gitlab_client.py"],
        "primary_category": "SECURITY",
    },
]


# ── pytest test functions ─────────────────────────────────────────────────────

def test_section_heading_and_table():
    parts = _render_expertise_section(EXPERTISE_MAP)
    rendered = "\n".join(parts)
    assert "## 👤 Expertise Map" in rendered
    assert "decided_by" in rendered
    assert "| Person | Memories | Primary Area | Top Files |" in rendered
    assert "|--------|" in rendered


def test_person_rows():
    parts = _render_expertise_section(EXPERTISE_MAP)
    rendered = "\n".join(parts)
    assert "@shruti" in rendered
    assert "@arya" in rendered
    assert "#001" in rendered and "#003" in rendered
    assert "#002" in rendered
    assert "ARCHITECTURE" in rendered
    assert "SECURITY" in rendered
    assert "`legacy/agents/cortexkeeper.py`" in rendered
    assert "`legacy/core/gitlab_client.py`" in rendered


def test_top_files_truncated():
    many_files_entry = [{
        "person": "@shruti",
        "memory_ids": ["001"],
        "top_files": ["a.py", "b.py", "c.py", "d.py", "e.py"],
        "primary_category": "PERFORMANCE",
    }]
    long_parts = _render_expertise_section(many_files_entry)
    long_rendered = "\n".join(long_parts)
    assert "`a.py`" in long_rendered and "`b.py`" in long_rendered and "`c.py`" in long_rendered
    assert "`d.py`" not in long_rendered
    assert "`e.py`" not in long_rendered


def test_missing_fields_default_gracefully():
    sparse_entry = [{"person": "@arya", "memory_ids": ["005"]}]
    sparse_parts = _render_expertise_section(sparse_entry)
    sparse_rendered = "\n".join(sparse_parts)
    assert "@arya" in sparse_rendered
    assert "#005" in sparse_rendered
    assert "| — |" in sparse_rendered or "| —" in sparse_rendered


def test_empty_expertise_map_omits_section():
    body_no_expertise = render_body_with_expertise([], DATE)
    assert "👤 Expertise Map" not in body_no_expertise
    assert "CORTEX Health Report" in body_no_expertise


def test_expertise_section_in_full_body():
    body_with_expertise = render_body_with_expertise(EXPERTISE_MAP, DATE)
    assert "👤 Expertise Map" in body_with_expertise
    assert "@shruti" in body_with_expertise
    assert "@arya" in body_with_expertise
    assert body_with_expertise.index("👤 Expertise Map") < body_with_expertise.index("Generated by CORTEX CORTEXCAST")
    assert "CORTEX Health Report" in body_with_expertise
    assert "All Memories Healthy" in body_with_expertise


def test_multiple_memory_ids_joined():
    multi_mem = [{"person": "@shruti", "memory_ids": ["001", "002", "005"], "top_files": [], "primary_category": "DATA"}]
    multi_parts = _render_expertise_section(multi_mem)
    multi_rendered = "\n".join(multi_parts)
    assert "#001, #002, #005" in multi_rendered


def test_single_person_map():
    single = [{"person": "@arya", "memory_ids": ["003"], "top_files": ["core/auth.py"], "primary_category": "SECURITY"}]
    single_parts = _render_expertise_section(single)
    single_rendered = "\n".join(single_parts)
    assert single_rendered.count("| @arya") == 1
    assert "`core/auth.py`" in single_rendered


# ── standalone execution (python tests/test_expertise_rendering.py) ───────────

if __name__ == "__main__":
    failures = 0

    def check(name, condition, detail=""):
        global failures
        if condition:
            print(f"  PASS  {name}")
        else:
            print(f"  FAIL  {name}" + (f": {detail}" if detail else ""))
            failures += 1

    print("=== Test 1: section heading and table structure ===")
    parts = _render_expertise_section(EXPERTISE_MAP)
    rendered = "\n".join(parts)
    check("heading present", "## 👤 Expertise Map" in rendered)
    check("intro line present", "decided_by" in rendered)
    check("table header row present", "| Person | Memories | Primary Area | Top Files |" in rendered)
    check("separator row present", "|--------|" in rendered)

    print()
    print("=== Test 2: person rows rendered correctly ===")
    check("@shruti row present", "@shruti" in rendered)
    check("@arya row present", "@arya" in rendered)
    check("shruti memory ids", "#001" in rendered and "#003" in rendered)
    check("arya memory id", "#002" in rendered)
    check("shruti category", "ARCHITECTURE" in rendered)
    check("arya category", "SECURITY" in rendered)
    check("shruti file backticked", "`legacy/agents/cortexkeeper.py`" in rendered)
    check("arya file backticked", "`legacy/core/gitlab_client.py`" in rendered)

    print()
    print("=== Test 3: top_files capped at 3 in rendered output ===")
    many_files_entry = [{
        "person": "@shruti",
        "memory_ids": ["001"],
        "top_files": ["a.py", "b.py", "c.py", "d.py", "e.py"],
        "primary_category": "PERFORMANCE",
    }]
    long_parts = _render_expertise_section(many_files_entry)
    long_rendered = "\n".join(long_parts)
    check("first 3 files present", "`a.py`" in long_rendered and "`b.py`" in long_rendered and "`c.py`" in long_rendered)
    check("4th file NOT rendered", "`d.py`" not in long_rendered)
    check("5th file NOT rendered", "`e.py`" not in long_rendered)

    print()
    print("=== Test 4: missing optional fields are handled ===")
    sparse_entry = [{"person": "@arya", "memory_ids": ["005"]}]
    sparse_parts = _render_expertise_section(sparse_entry)
    sparse_rendered = "\n".join(sparse_parts)
    check("person still rendered", "@arya" in sparse_rendered)
    check("memory id still rendered", "#005" in sparse_rendered)
    check("primary_category defaults to dash", "| — |" in sparse_rendered or "| —" in sparse_rendered)
    check("no file crash when top_files absent", True)

    print()
    print("=== Test 5: empty expertise_map -> section omitted ===")
    body_no_expertise = render_body_with_expertise([], DATE)
    check("no heading when map empty", "👤 Expertise Map" not in body_no_expertise)
    check("health report still present", "CORTEX Health Report" in body_no_expertise)

    print()
    print("=== Test 6: expertise section present and ordered in full body ===")
    body_with_expertise = render_body_with_expertise(EXPERTISE_MAP, DATE)
    check("heading present in full body", "👤 Expertise Map" in body_with_expertise)
    check("@shruti in full body", "@shruti" in body_with_expertise)
    check("@arya in full body", "@arya" in body_with_expertise)
    check("section before footer", body_with_expertise.index("👤 Expertise Map") < body_with_expertise.index("Generated by CORTEX CORTEXCAST"))
    check("health report heading present", "CORTEX Health Report" in body_with_expertise)
    check("all memories healthy section present", "All Memories Healthy" in body_with_expertise)

    print()
    print("=== Test 7: multiple memory ids joined with commas ===")
    multi_mem = [{"person": "@shruti", "memory_ids": ["001", "002", "005"], "top_files": [], "primary_category": "DATA"}]
    multi_parts = _render_expertise_section(multi_mem)
    multi_rendered = "\n".join(multi_parts)
    check("ids joined by comma-space", "#001, #002, #005" in multi_rendered)

    print()
    print("=== Test 8: single-person map ===")
    single = [{"person": "@arya", "memory_ids": ["003"], "top_files": ["core/auth.py"], "primary_category": "SECURITY"}]
    single_parts = _render_expertise_section(single)
    single_rendered = "\n".join(single_parts)
    check("one data row", single_rendered.count("| @arya") == 1)
    check("file rendered", "`core/auth.py`" in single_rendered)

    print()
    if failures == 0:
        print("All tests PASSED")
        sys.exit(0)
    else:
        print(f"{failures} test(s) FAILED")
        sys.exit(1)
